def _sha512crypt(password: str) -> str:
    """Return a real SHA-512 crypt hash via openssl."""
    try:
        proc = subprocess.run(
            ['openssl', 'passwd', '-6', '-salt', 'tvtv2026', password],
            capture_output=True, text=True, check=False, timeout=5,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            return proc.stdout.strip()
    except Exception:
        pass
    # Fallback to precomputed SHA-512 hash for 'tvtv' with salt 'tvtv2026'
    return "$6$tvtv2026$dbd.bIB6vHtdfhOgQvdigyFFvnyTlomCarkjxFMO3SdVw0Hi1fqzh7UzLQoojVDKOFKYDk6jyuiZjtqfqCnWk1"



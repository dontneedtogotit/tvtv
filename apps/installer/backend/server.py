_ISO_BUILD_STATUS = {
    'running': False,
    'progress': '',
    'log': [],
    'output_iso': '',
    'error': '',
}


def _run_remaster_task():
    global _ISO_BUILD_STATUS
    _ISO_BUILD_STATUS['running'] = True
    _ISO_BUILD_STATUS['error'] = ''
    _ISO_BUILD_STATUS['progress'] = 'Starting ISO remastering...'

    remaster_script = ISO_DIR / 'remaster.sh'
    if not remaster_script.exists():
        _ISO_BUILD_STATUS['running'] = False
        _ISO_BUILD_STATUS['error'] = f'Remaster script not found at {remaster_script}'
        return

    try:
        proc = subprocess.Popen(
            ['bash', str(remaster_script)],
            cwd=str(PROJECT_ROOT),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        log_lines = []
        if proc.stdout:
            for line in proc.stdout:
                clean = line.strip()
                if clean:
                    log_lines.append(clean)
                    _ISO_BUILD_STATUS['progress'] = clean
                    _ISO_BUILD_STATUS['log'] = log_lines[-50:]
        proc.wait()
        if proc.returncode == 0:
            _ISO_BUILD_STATUS['progress'] = 'ISO build complete!'
            _ISO_BUILD_STATUS['output_iso'] = str(PROJECT_ROOT / 'iso-output' / 'tvtv-installer.iso')
        else:
            _ISO_BUILD_STATUS['error'] = f'Remaster process exited with code {proc.returncode}'
    except Exception as e:
        _ISO_BUILD_STATUS['error'] = str(e)
    finally:
        _ISO_BUILD_STATUS['running'] = False


@router.post('/bake-iso')
def bake_iso(background_tasks: BackgroundTasks):
    """Triggers ISO remastering in background."""
    global _ISO_BUILD_STATUS
    if _ISO_BUILD_STATUS['running']:
        return {'status': 'already_running', 'progress': _ISO_BUILD_STATUS['progress']}
    background_tasks.add_task(_run_remaster_task)
    return {'status': 'started', 'message': 'ISO remastering started in background.'}



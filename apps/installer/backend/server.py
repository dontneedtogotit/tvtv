@router.get('/disks')
def list_disks():
    """Returns detected physical block devices."""
    disks = []
    try:
        proc = subprocess.run(
            ['lsblk', '-d', '-n', '-J', '-o', 'NAME,SIZE,MODEL,TYPE,TRAN,ROTA'],
            capture_output=True, text=True, check=False, timeout=5,
        )
        if proc.returncode == 0 and proc.stdout.strip():
            data = json.loads(proc.stdout)
            for dev in data.get('blockdevices', []):
                if dev.get('type') == 'disk':
                    name = dev.get('name', '')
                    model = (dev.get('model') or '').strip()
                    size = dev.get('size', '')
                    tran = dev.get('tran') or 'nvme' if 'nvme' in name else 'sata'
                    disks.append({
                        'device': f'/dev/{name}',
                        'name': name,
                        'size': size,
                        'model': model or 'Internal Drive',
                        'transport': tran,
                    })
    except Exception:
        pass
    if not disks:
        disks = [
            {'device': '/dev/nvme0n1', 'name': 'nvme0n1', 'size': '500G', 'model': 'NVMe SSD (Auto-detected)', 'transport': 'nvme'},
            {'device': '/dev/sda', 'name': 'sda', 'size': '256G', 'model': 'SATA SSD / HDD', 'transport': 'sata'},
        ]
    return {'disks': disks}


@router.get('/wifi-scan')
def scan_wifi():
    """Scans and returns nearby Wi-Fi SSIDs."""
    networks = []
    try:
        proc = subprocess.run(
            ['nmcli', '-t', '-f', 'SSID,SIGNAL,SECURITY', 'dev', 'wifi', 'list'],
            capture_output=True, text=True, check=False, timeout=8,
        )
        if proc.returncode == 0:
            seen = set()
            for line in proc.stdout.splitlines():
                parts = line.split(':')
                if parts and parts[0] and parts[0] not in seen:
                    seen.add(parts[0])
                    signal = int(parts[1]) if len(parts) > 1 and parts[1].isdigit() else 75
                    sec = parts[2] if len(parts) > 2 else "WPA2"
                    networks.append({'ssid': parts[0], 'signal': signal, 'security': sec})
    except Exception:
        pass
    return {'networks': networks}


@router.post('/generate')
def generate_installer(req: InstallerRequest):
    """Generates the Ubuntu autoinstall cloud-config YAML and saves it."""
    user_data, tv_conf = _build_user_data(req)

    out_path = '/tmp/tvtv-installer-user-data.yaml'
    try:
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, 'w') as f:
            f.write(user_data)
    except Exception as e:
        raise HTTPException(500, f'Failed to write installer config: {e}')

    # Also update in-tree iso/autoinstall/user-data if available
    in_tree_autoinstall = AUTOINSTALL_DIR / 'user-data'
    try:
        if AUTOINSTALL_DIR.exists():
            in_tree_autoinstall.write_text(user_data)
    except Exception:
        pass

    return {
        'status': 'ok',
        'path': out_path,
        'user_data': user_data,
        'tv_conf': tv_conf,
        'message': 'Autoinstall configuration generated successfully.',
    }


